export const meta = {
  name: 'port-jampgame',
  description: 'One-shot jampgame logic port: land skeletons, fill all function bodies per settled fork rulings, integrate to green, aggregate parked escalations',
  whenToUse: 'The jampgame mega-pass. Requires: FROZEN Group-A docs, settled fork rulings (docs/handoffs/jampgame-fork-discovery.md), staged skeletons (tools/closure-prototype/out/skel/), the fn manifest. Launch on a fresh usage window — this is the largest single burn of the project.',
  phases: [
    { title: 'Land', detail: 'wire the 88 staged skeleton files into crates/mp/game, green, checkpoint commit' },
    { title: 'Port', detail: 'one porter per .c file fills bodies; escalations parked, never blocking' },
    { title: 'Integrate', detail: 'cargo-check fixer loop until green' },
    { title: 'Aggregate', detail: 'collect parked escalations into the session report' },
  ],
}

// args: { worktree?, skelDir?, manifestPath?, maxFiles?, fixerRounds? }
const WT = (args && args.worktree) || '/Users/milohehmsoth/Developer/Milo/jka-rust/.claude/worktrees/agent-a43cc53200d2fdf54'
const MAIN = '/Users/milohehmsoth/Developer/Milo/jka-rust'
const SKEL = (args && args.skelDir) || `${MAIN}/tools/closure-prototype/out/skel`
const MANIFEST = (args && args.manifestPath) || `${MAIN}/tools/closure-prototype/out/jampgame-fn-manifest.json`
const MAX_FILES = (args && args.maxFiles) || 999
const FIXER_ROUNDS = (args && args.fixerRounds) || 4

const STYLE = `HOUSE RULES: doc-comment + Source cite on every item (oracle/codemp/game/<file>:<lines>); preserve Raven comments that clarify behavior; state conclusions not derivations; //TODO: Port <subject> + // Source: for anything unported; behavioral parity per porting-rules SA — no speculative behavior, port faithfully even if ugly; UB sites get the one defined behavior + <=2-line note per S19. NEVER touch oracle/. NEVER add a co-author trailer.`

const PARK = `PARK PROTOCOL: if something genuinely cannot be decided from the frozen docs + rulings + porting rules, DO NOT BLOCK and DO NOT INVENT: leave that function's body todo!("Port <Fn> — parked: <topic>"), add // PORT-ESCALATION(<topic>): <one-line question> above it, count it, and continue with the rest of the file. Escalations are expected and cheap; wrong inventions are expensive.`

phase('Land')
log('Landing 88 skeleton files + pre-generated boilerplate into crates/mp/game on the skeleton branch')
const landed = await agent(
  `You are landing the staged jampgame skeletons AND the pre-generated boilerplate. Worktree: ${WT} (branch skeleton — verify with git branch, pull nothing). Staged skeletons: ${SKEL}/*.rs (88 files, generated by fnskel.py; faithful signatures, todo!() bodies). Pre-generated boilerplate: ${MAIN}/tools/closure-prototype/out/gen/{game_cvars.rs, ent_fn_enums.rs, trap_wrappers.rs} — land these too (GameCvars struct into the GameWorld family, fn-ID enums + dispatch match skeletons, trap wrappers merged into trap.rs without clobbering the live Printf). Manifest: ${MANIFEST}.
Task: wire everything into crates/mp/game/src/ following the existing crate layout (one module per oracle .c file; keep the existing world/, trap.rs, lib.rs structure intact — skeletons ADD modules, they must not clobber the slice-0 live code: vmMain path, g_init_game, g_shutdown_game stay as-is; where a skeleton fn already exists live, keep the live one and drop the skeleton duplicate). Add mod declarations. Resolve the 17 unported-type params with //TODO: Port markers as the generator emitted them. cargo check --workspace must be GREEN. Commit on skeleton: "Mega-pass checkpoint: land jampgame fn skeletons + generated boilerplate". ${STYLE}
Return JSON: {landed_files, skipped_dupes, green: true/false, commit}`,
  { phase: 'Land', model: 'opus', schema: { type: 'object', properties: { landed_files: { type: 'number' }, skipped_dupes: { type: 'array', items: { type: 'string' } }, green: { type: 'boolean' }, commit: { type: 'string' } }, required: ['green'] } }
)
if (!landed || !landed.green) return { aborted: 'skeleton landing not green', landed }

phase('Port')
const manifest = await agent(
  `Read ${MANIFEST} (JSON). Return ONLY a JSON array of the distinct .c file names (e.g. "g_combat.c") with their function counts and total LOC, largest first: [{file, fns, loc}]. No prose.`,
  { phase: 'Port', label: 'read-manifest', model: 'haiku', effort: 'low', schema: { type: 'object', properties: { files: { type: 'array', items: { type: 'object', properties: { file: { type: 'string' }, fns: { type: 'number' }, loc: { type: 'number' } }, required: ['file'] } } }, required: ['files'] } }
)
// Idempotency inventory: modules already carrying a PORT-COMPLETE header are done —
// a relaunch after any interruption ports only the remainder.
const inv = await agent(
  `In ${WT}, run: grep -rl "PORT-COMPLETE:" crates/mp/game/src/ 2>/dev/null and map each hit back to its oracle .c name (the module doc-comments cite it; the filename correspondence is 1:1, e.g. g_combat.rs -> g_combat.c). Return JSON {done: ["g_combat.c", ...]} — empty array if none. No prose.`,
  { phase: 'Port', label: 'inventory-done', model: 'haiku', effort: 'low', schema: { type: 'object', properties: { done: { type: 'array', items: { type: 'string' } } }, required: ['done'] } }
)
const doneSet = new Set((inv && inv.done) || [])
const files = (manifest.files || []).filter(f => !doneSet.has(f.file)).slice(0, MAX_FILES)
log(`Porting ${files.length} files (${doneSet.size} already PORT-COMPLETE from a prior run)`)

const PORT_SCHEMA = { type: 'object', properties: { file: { type: 'string' }, fns_ported: { type: 'number' }, fns_parked: { type: 'number' }, escalations: { type: 'array', items: { type: 'object', properties: { fn: { type: 'string' }, topic: { type: 'string' }, question: { type: 'string' } }, required: ['fn', 'question'] } } }, required: ['file', 'fns_ported'] }

// Model ladder: transcription is mechanical (all forks settled) — Sonnet default,
// Haiku for small leaf files, Opus only for the monster files / SCC-cluster homes.
const OPUS_FILES = new Set(['ai_main.c', 'w_saber.c', 'g_saga.c', 'g_combat.c', 'g_active.c', 'g_client.c', 'g_vehicles.c', 'NPC_AI_Jedi.c'])
const tierFor = f => OPUS_FILES.has(f.file) || f.loc > 4500 ? 'opus' : f.loc < 600 ? 'haiku' : 'sonnet'

const results = await parallel(files.map(f => () => {
  if (budget.total && budget.remaining() < 250_000) { log(`BUDGET GUARD: skipping ${f.file} (${Math.round(budget.remaining()/1000)}k left)`); return null }
  const model = tierFor(f)
  return agent(
    `You are porting ONE file of the jampgame logic port: ${f.file} (${f.fns} functions, ${f.loc} LOC). Worktree: ${WT}, branch skeleton.
YOUR ENTIRE INPUT IS TWO THINGS — read nothing else, explore nothing:
1. Your packet: ${MAIN}/tools/closure-prototype/out/packets/${f.file}.md — contains the settled fork rulings (LAW), the complete cited oracle source, your functions' manifest rows, and the resolved Rust signature of every out-of-file symbol you call.
2. Your skeleton module under crates/mp/game/src/ in the worktree (every fn is a todo!() with signature + cite).
Fill every function body: faithful transcription of the oracle logic into the settled Rust shapes per the packet's rulings digest.
${STYLE}
${PARK}
Cross-file calls: use the packet's resolved signatures verbatim — never re-declare, never grep the tree. Traps: the wrappers are pre-generated in trap.rs — call them; if one you need is missing, add it copying the adjacent shape exactly. bg_ calls marked UNPORTED in the packet: park that fn with PORT-ESCALATION(bg-dep). GameWorld/GameCvars fields you need that don't exist: ADD them (additive; keep Raven's names). Fn-pointer assignments: use the pre-generated fn-ID enums (EntThink:: etc.).
WRITE DISCIPLINE: emit the module in a FEW LARGE Write/Edit calls (whole-file or large-section), not dozens of small edits. Do NOT run cargo (parallel porters share the tree). Do NOT commit.
COMPLETION MARKER: if the module already starts with a "// PORT-COMPLETE:" line, return {file: "${f.file}", fns_ported: 0, fns_parked: 0, escalations: []} immediately — it was finished by a prior run. Otherwise, when every fn is implemented-or-parked, add "// PORT-COMPLETE: ${f.file} <ported>/<parked>" as the module's first line.
Return JSON: {file, fns_ported, fns_parked, escalations:[{fn, topic, question}]}`,
    { label: `port:${f.file}`, phase: 'Port', model, effort: model === 'opus' ? 'medium' : 'low', schema: PORT_SCHEMA }
  )
}))
const ported = results.filter(Boolean)
const skipped = files.length - ported.length
log(`Ported ${ported.length}/${files.length} files (${skipped} budget-skipped)`)

// WIP safety commit: raw porter output is durable even if integration never runs
// (clearly labeled non-checkpoint; DEC-10 green checkpoints come from the fixer).
await agent(
  `In ${WT}: git add -A && git commit -m "Mega-pass WIP: raw porter output (pre-integration, NOT a green checkpoint)". NEVER add a co-author trailer. Return JSON {commit: "<hash or 'nothing-to-commit'>"}.`,
  { phase: 'Integrate', label: 'wip-commit', model: 'haiku', effort: 'low', schema: { type: 'object', properties: { commit: { type: 'string' } }, required: ['commit'] } }
)

phase('Integrate')
let green = false, round = 0
while (!green && round < FIXER_ROUNDS) {
  round++
  const fix = await agent(
    `Integration fixer, round ${round}. Worktree: ${WT} (branch skeleton). ~${ported.length} jampgame files just had bodies filled by parallel porters who never ran cargo. Run cargo check --workspace 2>&1, triage ALL errors, and fix them MECHANICALLY: missing mod/use wiring, GameWorld field collisions from parallel adds (merge duplicates, keep Raven names), trap wrapper dupes, type mismatches with an obvious faithful fix, turbofish where inference fails. Anything requiring a real design judgment: park it (todo!() + // PORT-ESCALATION comment) rather than invent. ${STYLE}
When green (or when only parked items remain and the tree compiles): commit on skeleton as "Mega-pass checkpoint: integration round ${round} green". Return JSON {green: true/false, errors_fixed, parked_added, commit}.`,
    { label: `fix:round${round}`, phase: 'Integrate', model: round <= 2 ? 'sonnet' : 'opus', schema: { type: 'object', properties: { green: { type: 'boolean' }, errors_fixed: { type: 'number' }, parked_added: { type: 'number' }, commit: { type: 'string' } }, required: ['green'] } }
  )
  green = !!(fix && fix.green)
  log(`Integration round ${round}: ${green ? 'GREEN' : 'not green yet'}`)
}

phase('Aggregate')
const escalations = ported.flatMap(r => (r.escalations || []).map(e => ({ ...e, file: r.file })))
const totals = {
  files_ported: ported.length,
  files_skipped_budget: skipped,
  fns_ported: ported.reduce((a, r) => a + (r.fns_ported || 0), 0),
  fns_parked: ported.reduce((a, r) => a + (r.fns_parked || 0), 0),
  integration_green: green,
  escalation_count: escalations.length,
}
log(`DONE: ${totals.fns_ported} fns ported, ${totals.fns_parked} parked, green=${green}`)
return { totals, escalations }
