#!/usr/bin/env python3
"""Extract the LIVE msg_hData table from the unmodified oracle msg.cpp and emit
a C header (build/msg_hdata.h) the harness compiles in.

The oracle file carries TWO `int msg_hData[256]` definitions:
  - msg.cpp:2696  the old Quake-3 table (3163878, ...) — DEAD (compiled out).
  - msg.cpp:2958  the LIVE table, immediately after the `// Q3 TA freq. table.`
    marker (250315, ...).
We anchor on that marker so we can never pick up the stale one.
oracle/ is never edited.
"""
import re
import sys

MARKER = "// Q3 TA freq. table."


def main(msg_cpp: str, out_h: str) -> None:
    with open(msg_cpp, "r", encoding="latin-1") as f:
        text = f.read()

    idx = text.find(MARKER)
    if idx < 0:
        sys.exit(f"marker {MARKER!r} not found in {msg_cpp}")

    # After the marker, find the opening brace of the array initialiser.
    brace = text.find("{", idx)
    if brace < 0:
        sys.exit("no '{' after marker")
    end = text.find("}", brace)
    if end < 0:
        sys.exit("no '}' closing the initialiser")

    body = text[brace + 1 : end]
    # Each value is the leading integer of a comma-separated entry.
    vals = re.findall(r"(-?\d+)\s*,", body)
    if len(vals) < 256:
        sys.exit(f"expected >=256 values, got {len(vals)}")
    vals = vals[:256]

    with open(out_h, "w", encoding="ascii") as f:
        f.write("// GENERATED by extract_table.py from the LIVE oracle table\n")
        f.write("// (oracle/codemp/qcommon/msg.cpp, after '// Q3 TA freq. table.').\n")
        f.write("// Do not hand-edit. oracle/ is never touched.\n")
        f.write("static int msg_hData[256] = {\n")
        for i in range(0, 256, 8):
            row = ", ".join(vals[i : i + 8])
            f.write(f"\t{row},\n")
        f.write("};\n")
    print(f"extract_table: wrote {out_h} ({vals[0]}..{vals[255]})")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
