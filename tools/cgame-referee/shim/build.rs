//! Generates the serializer tables from the two committed manifests
//! (`../trap-shapes.json`, `../export-shapes.json`) into
//! `$OUT_DIR/manifest_tables.rs`, and compiles the C variadic trampoline.
//!
//! We generate at build time (build.rs) rather than checking in a generated .rs
//! so the tables can never drift from the manifests - edit the JSON, rebuild,
//! the shim serializes the new shape. serde_json is a build-dependency only, so
//! the runtime cdylib stays lean (no JSON parser shipped in the module).

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use serde_json::Value;

fn main() {
    println!("cargo:rerun-if-changed=src/trampoline.c");
    println!("cargo:rerun-if-changed=../trap-shapes.json");
    println!("cargo:rerun-if-changed=../export-shapes.json");

    cc::Build::new()
        .file("src/trampoline.c")
        .warnings(true)
        .compile("cgame_shim_trampoline");

    let out_dir = env::var("OUT_DIR").expect("OUT_DIR");
    let mut src = String::new();
    src.push_str("// GENERATED by build.rs from the cgame-referee manifests. Do not edit.\n\n");
    gen_traps(&mut src, "../trap-shapes.json");
    gen_exports(&mut src, "../export-shapes.json");
    fs::write(Path::new(&out_dir).join("manifest_tables.rs"), src).expect("write tables");
}

/// Maps a manifest arg `kind` string to the `ArgKind` variant path.
fn arg_kind(kind: &str) -> &'static str {
    match kind {
        "scalar" => "ArgKind::Scalar",
        "in_str" => "ArgKind::InStr",
        "in_buf" => "ArgKind::InBuf",
        "out_buf" => "ArgKind::OutBuf",
        "inout_buf" => "ArgKind::InoutBuf",
        "double_ptr" => "ArgKind::DoublePtr",
        "retained_ptr" => "ArgKind::RetainedPtr",
        other => panic!("unknown arg kind {other}"),
    }
}

fn trap_ret(ret: &str) -> &'static str {
    match ret {
        "void" => "RetKind::Void",
        "scalar" => "RetKind::Scalar",
        "handle" => "RetKind::Handle",
        "float" => "RetKind::Float",
        other => panic!("unknown trap ret {other}"),
    }
}

fn export_ret(ret: &str) -> &'static str {
    match ret {
        "void" => "ExportRet::Void",
        "scalar" => "ExportRet::Scalar",
        "ptr_opaque" => "ExportRet::PtrOpaque",
        "ptr_deref" => "ExportRet::PtrDeref",
        other => panic!("unknown export ret {other}"),
    }
}

fn gen_traps(out: &mut String, path: &str) {
    let doc: Value = serde_json::from_str(&fs::read_to_string(path).expect("read trap json"))
        .expect("parse trap json");
    let traps = doc["traps"].as_array().expect("traps array");

    out.push_str("pub static TRAP_TABLE: &[TrapShape] = &[\n");
    for t in traps {
        let num = t["num"].as_i64().unwrap();
        let name = t["name"].as_str().unwrap();
        let ret = trap_ret(t["ret"].as_str().unwrap());
        // README: the G2 and FX families stage their big structs into the
        // engine-retained shared buffer. The manifest carries no shared flag
        // (see README 'Things flagged as not certain'), so we derive the set by
        // family name - the recorder dumps the 2048-byte region around these.
        let dumps_shared = name.starts_with("CG_G2_") || name.starts_with("CG_FX_");

        let mut args_lit = String::new();
        for a in t["args"].as_array().unwrap() {
            let kind = arg_kind(a["kind"].as_str().unwrap());
            let size_of = a["size_of"].as_u64().unwrap_or(0);
            let len_arg = a["len_arg"].as_i64().unwrap_or(-1);
            // element stride for len_arg buffers: the named size_of, else 1 byte.
            let elem = if size_of > 0 { size_of } else { 1 };
            write!(
                args_lit,
                "ArgShape {{ kind: {kind}, size_of: {size_of}, len_arg: {len_arg}, elem_size: {elem} }}, "
            )
            .unwrap();
        }
        write!(
            out,
            "    TrapShape {{ num: {num}, name: {name:?}, ret: {ret}, dumps_shared: {dumps_shared}, args: &[{args_lit}] }},\n"
        )
        .unwrap();
    }
    out.push_str("];\n\n");
}

fn gen_exports(out: &mut String, path: &str) {
    let doc: Value = serde_json::from_str(&fs::read_to_string(path).expect("read export json"))
        .expect("parse export json");
    let exports = doc["exports"].as_array().expect("exports array");

    out.push_str("pub static EXPORT_TABLE: &[ExportShape] = &[\n");
    for e in exports {
        let num = e["num"].as_i64().unwrap();
        let name = e["name"].as_str().unwrap();
        let ret = export_ret(e["ret"].as_str().unwrap());
        let ret_size = e["ret_size_of"].as_u64().unwrap_or(0);
        let shared = match e.get("shared_buffer").and_then(|v| v.as_str()) {
            None => "SharedKind::None",
            Some("in") => "SharedKind::In",
            Some("out") => "SharedKind::Out",
            Some("inout") => "SharedKind::Inout",
            Some(other) => panic!("unknown shared_buffer {other}"),
        };

        let mut args_lit = String::new();
        for a in e["args"].as_array().unwrap() {
            let kind = arg_kind(a["kind"].as_str().unwrap());
            let size_of = a["size_of"].as_u64().unwrap_or(0);
            write!(
                args_lit,
                "ExportArg {{ kind: {kind}, size_of: {size_of} }}, "
            )
            .unwrap();
        }
        write!(
            out,
            "    ExportShape {{ num: {num}, name: {name:?}, ret: {ret}, ret_size_of: {ret_size}, shared: {shared}, args: &[{args_lit}] }},\n"
        )
        .unwrap();
    }
    out.push_str("];\n\n");
}
