#!/usr/bin/env python3
"""PROTOTYPE — throwaway. Renderer type inventory for the client-port R1
stage.

Runs the sweep.py type extractor over the renderer-owned root-type headers
named in the renderer plan (`tr_local.h`, the module-facing `tr_types.h`,
and the shared BSP/model file-format header `qfiles.h`) from one mp-renderer
parse, cross-references each type against the ported Rust tree
(crates/mp/renderer — via closure.scan_ported's verified badges), and
classifies each PORTED / STUB / MISSING. Emits out/renderer/
renderer-type-inventory.{json,md}. Sibling of uitypes.py (ui's U0 analog).

tr_types.h physically lives at `codemp/cgame/tr_types.h` (shared cgame/
renderer seam header, pulled in transitively via tr_local.h -> tr_public.h),
not under codemp/renderer/ — the oracle-relative header suffix passed to
sweep.py is a path SUFFIX match (closure.decl_in_header), so this works from
one mp-renderer parse without a separate profile entry. qfiles.h is NOT
renderer-exclusive (collision/qcommon consume the same BSP lump structs) —
included in full per the R1 work order ("qfiles.h renderer sections"); no
section filter exists in sweep.py, so this inventories the whole header and
the report notes the shared ownership.

`sweep.py mp-renderer --header <h> --json` already produces the per-type
badge (a size-assert-verified ported status). This wrapper fans out over the
header set, maps the badge glyph to a PORTED/STUB/MISSING verdict, and
renders the two artifacts.

Usage:
  .venv/bin/python rtypes.py [--out DIR]
"""
import argparse
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

# renderer root-type headers named in the R1 work order (docs/plans/
# 2026-07-24-client-port/renderer-plan.md). tr_types.h is oracle-relative to
# codemp/cgame/, not codemp/renderer/ — see module docstring.
HEADERS = ["renderer/tr_local.h", "cgame/tr_types.h", "qcommon/qfiles.h"]


def badge_verdict(badge: str) -> str:
    """Map a closure.make_badger glyph to a PORTED / STUB / MISSING verdict.
    ☑ = declared + size-assert-verified; ◐ = declared-no-assert or a TODO
    marker (a stub); ✗ = declared but size MISMATCH (a broken stub); ☐ = no
    declaration at all."""
    if badge.startswith("☑"):      # ☑ declared + verified
        return "PORTED"
    if badge.startswith("☐"):      # ☐ UNPORTED (no declaration)
        return "MISSING"
    if badge.startswith("✗"):      # ✗ declared but size MISMATCH
        return "STUB"
    if badge.startswith("◐"):      # ◐ TODO marker / declared-no-assert
        return "STUB"
    return "MISSING"


def sweep_header(header: str):
    r = subprocess.run(
        [str(HERE / ".venv/bin/python"), str(HERE / "sweep.py"), "mp-renderer",
         "--header", header, "--json"],
        capture_output=True, text=True, cwd=str(HERE))
    if r.returncode != 0:
        sys.exit(f"sweep failed for {header}:\n{r.stderr}")
    return json.loads(r.stdout or "[]")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default=str(HERE / "out" / "renderer"))
    args = ap.parse_args()
    outdir = Path(args.out)
    outdir.mkdir(parents=True, exist_ok=True)

    inventory = {}
    for h in HEADERS:
        rows = sweep_header(h)
        for r in rows:
            r["verdict"] = badge_verdict(r["badge"])
        inventory[h] = rows

    totals = {"PORTED": 0, "STUB": 0, "MISSING": 0}
    for rows in inventory.values():
        for r in rows:
            totals[r["verdict"]] += 1
    total_types = sum(totals.values())

    payload = {
        "module": "mp-renderer",
        "headers": HEADERS,
        "totals": totals,
        "total_types": total_types,
        "note": "qfiles.h is NOT renderer-exclusive (cm_*/collision consume "
                "the same BSP lump structs) — inventoried in full per the R1 "
                "work order; no header-section filter exists in sweep.py. "
                "tr_types.h lives at codemp/cgame/tr_types.h (the cgame/"
                "renderer module-facing seam), reached transitively via "
                "tr_local.h -> tr_public.h.",
        "by_header": inventory,
    }
    (outdir / "renderer-type-inventory.json").write_text(json.dumps(payload, indent=1))

    o = []
    o.append("# renderer type inventory (mp-renderer) — PORTED / STUB / MISSING\n")
    o.append("Generated by `tools/closure-prototype/rtypes.py` (fans "
             "`sweep.py mp-renderer --header <h> --json` over tr_local.h/"
             "tr_types.h/qfiles.h; badges are size-assert-verified against "
             "the ported Rust tree — crates/mp/renderer).\n")
    o.append("## Headline\n")
    o.append(f"- **Types owned by the three headers:** {total_types}")
    o.append(f"- **PORTED:** {totals['PORTED']}  ·  **STUB:** {totals['STUB']}  "
             f"·  **MISSING:** {totals['MISSING']}\n")
    o.append(f"{payload['note']}\n")
    for h in HEADERS:
        rows = inventory[h]
        o.append(f"## `{h}` — {len(rows)} types\n")
        if not rows:
            o.append("_Owns no types._\n")
            continue
        o.append("| type | kind | size | tier | verdict | Rust home / marker | oracle cite |")
        o.append("| --- | --- | ---: | --- | --- | --- | --- |")
        for r in sorted(rows, key=lambda r: r["name"]):
            home = r["badge"].split(" ", 1)[1] if " " in r["badge"] else r["badge"]
            o.append(f"| `{r['name']}` | {r['kind']} | {r['sizeB']}B | {r['tier']} "
                     f"| {r['verdict']} | {home} | {r['cite']} |")
        o.append("")
    (outdir / "renderer-type-inventory.md").write_text("\n".join(o))

    print(f"[rtypes] {total_types} types  "
          f"PORTED={totals['PORTED']} STUB={totals['STUB']} MISSING={totals['MISSING']}")
    print(f"[rtypes] wrote {outdir / 'renderer-type-inventory.json'}")
    print(f"[rtypes] wrote {outdir / 'renderer-type-inventory.md'}")


if __name__ == "__main__":
    main()
