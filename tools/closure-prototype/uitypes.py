#!/usr/bin/env python3
"""PROTOTYPE — throwaway. UI type inventory for the client-port U0 stage.

Runs the sweep.py type extractor over every ui-owned header (`ui_local.h`,
`ui_shared.h`, `ui_public.h`, `ui_force.h`, plus the shared `ui/menudef.h`)
from one mp-ui parse, cross-references each type against the ported Rust tree
(crates/mp/ui, crates/mp/uishared, crates/mp/abi/src/ui, crates/native/types —
via closure.scan_ported's verified badges), and classifies each PORTED / STUB /
MISSING. Emits out/ui/ui-type-inventory.{json,md}.

`sweep.py mp-ui --header <h> --json` already produces the per-type badge (a
size-assert-verified ported status). This wrapper just fans out over the header
set, maps the badge glyph to a PORTED/STUB/MISSING verdict, and renders the two
artifacts. menudef.h is a `#define`-only header (colors, ITEM_TYPE_* constants)
— it owns zero *types*; its constants are a separate const/enum porting concern.

Usage:
  .venv/bin/python uitypes.py [--out DIR]
"""
import argparse
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

# ui-owned headers, oracle-relative suffixes. menudef.h lives at oracle/ui/
# (shared, included as ../../ui/menudef.h by ui_shared.h), NOT codemp/ui/.
HEADERS = ["ui/ui_local.h", "ui/ui_shared.h", "ui/ui_public.h",
           "ui/ui_force.h", "ui/menudef.h"]


def badge_verdict(badge: str) -> str:
    """Map a closure.make_badger glyph to a PORTED / STUB / MISSING verdict.
    ☑ = declared + size-assert-verified; ◐ = declared-no-assert or a TODO
    marker (a stub); ✗ = declared but size MISMATCH (a broken stub); ☐ = no
    declaration at all."""
    if badge.startswith("☑"):      # ☑ declared + verified
        return "PORTED"
    if badge.startswith("☐"):      # ☐ UNPORTED (no declaration)
        return "MISSING"
    if badge.startswith("✗"):      # ✗ declared but size MISMATCH
        return "STUB"
    if badge.startswith("◐"):      # ◐ TODO marker / declared-no-assert
        return "STUB"
    return "MISSING"


def sweep_header(header: str):
    r = subprocess.run(
        [str(HERE / ".venv/bin/python"), str(HERE / "sweep.py"), "mp-ui",
         "--header", header, "--json"],
        capture_output=True, text=True, cwd=str(HERE))
    if r.returncode != 0:
        sys.exit(f"sweep failed for {header}:\n{r.stderr}")
    return json.loads(r.stdout or "[]")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default=str(HERE / "out" / "ui"))
    args = ap.parse_args()
    outdir = Path(args.out)
    outdir.mkdir(parents=True, exist_ok=True)

    inventory = {}
    for h in HEADERS:
        rows = sweep_header(h)
        for r in rows:
            r["verdict"] = badge_verdict(r["badge"])
        inventory[h] = rows

    totals = {"PORTED": 0, "STUB": 0, "MISSING": 0}
    for rows in inventory.values():
        for r in rows:
            totals[r["verdict"]] += 1
    total_types = sum(totals.values())

    payload = {
        "module": "mp-ui",
        "headers": HEADERS,
        "totals": totals,
        "total_types": total_types,
        "note": "menudef.h is #define-only (owns 0 types; constants are a "
                "separate const/enum port). ui_force.h owns 0 types (fn "
                "prototypes + extern globals only — the uiForceSide/Rank/Used "
                "externs fold into UiWorld per the scoping doc).",
        "by_header": inventory,
    }
    (outdir / "ui-type-inventory.json").write_text(json.dumps(payload, indent=1))

    o = []
    o.append("# ui type inventory (mp-ui) — PORTED / STUB / MISSING\n")
    o.append("Generated by `tools/closure-prototype/uitypes.py` (fans "
             "`sweep.py mp-ui --header <h> --json` over the ui-owned headers; "
             "badges are size-assert-verified against the ported Rust tree — "
             "crates/mp/ui, crates/mp/uishared, crates/mp/abi/src/ui, "
             "crates/native/types).\n")
    o.append("## Headline\n")
    o.append(f"- **Types owned by ui headers:** {total_types}")
    o.append(f"- **PORTED:** {totals['PORTED']}  ·  **STUB:** {totals['STUB']}  "
             f"·  **MISSING:** {totals['MISSING']}\n")
    o.append(f"{payload['note']}\n")
    for h in HEADERS:
        rows = inventory[h]
        o.append(f"## `{h}` — {len(rows)} types\n")
        if not rows:
            o.append("_Owns no types._\n")
            continue
        o.append("| type | kind | size | tier | verdict | Rust home / marker | oracle cite |")
        o.append("| --- | --- | ---: | --- | --- | --- | --- |")
        for r in sorted(rows, key=lambda r: r["name"]):
            home = r["badge"].split(" ", 1)[1] if " " in r["badge"] else r["badge"]
            o.append(f"| `{r['name']}` | {r['kind']} | {r['sizeB']}B | {r['tier']} "
                     f"| {r['verdict']} | {home} | {r['cite']} |")
        o.append("")
    (outdir / "ui-type-inventory.md").write_text("\n".join(o))

    print(f"[uitypes] {total_types} types  "
          f"PORTED={totals['PORTED']} STUB={totals['STUB']} MISSING={totals['MISSING']}")
    print(f"[uitypes] wrote {outdir / 'ui-type-inventory.json'}")
    print(f"[uitypes] wrote {outdir / 'ui-type-inventory.md'}")


if __name__ == "__main__":
    main()
