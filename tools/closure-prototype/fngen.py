# =========================================================== game_cvars.rs
def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    return text


# The mp-game Release TU defines (closure.py RAVEN_MODULES) — the parity
# target. _DEBUG / FINAL_BUILD / DEBUG_SABER_BOX are NOT defined there.
DEFINED = {"NDEBUG", "MISSIONPACK", "QAGAME", "_JK2"}


def preprocess(text):
    """Tiny #ifdef/#ifndef/#if 0/#else/#endif evaluator so the parsed table
    matches the Release compile (gameCvarTable carries several debug-only
    rows)."""
    out, keep = [], [True]
    for ln in text.splitlines():
        s = ln.strip()
        if s.startswith("#ifdef"):
            keep.append(keep[-1] and s.split()[1] in DEFINED)
        elif s.startswith("#ifndef"):
            keep.append(keep[-1] and s.split()[1] not in DEFINED)
        elif s.startswith("#if"):
            tok = s.split(None, 1)[1] if len(s.split(None, 1)) > 1 else "0"
            keep.append(keep[-1] and tok.strip() not in ("0",))
        elif s.startswith("#else"):
            keep[-1] = (not keep[-1]) and (len(keep) < 2 or keep[-2])
        elif s.startswith("#endif"):
            keep.pop()
        elif keep[-1]:
            out.append(ln)
    return "\n".join(out)


def split_top_level(text, sep=","):
    """Split on `sep` at brace/paren/quote depth 0."""
    out, buf, depth, instr = [], [], 0, False
    i = 0
    while i < len(text):
        ch = text[i]
        if instr:
            buf.append(ch)
            if ch == "\\":
                buf.append(text[i + 1])
                i += 2
                continue
            if ch == '"':
                instr = False
        elif ch == '"':
            instr = True
            buf.append(ch)
        elif ch in "{([":
            depth += 1
            buf.append(ch)
        elif ch in "})]":
            depth -= 1
            buf.append(ch)
        elif ch == sep and depth == 0:
            out.append("".join(buf).strip())
            buf = []
        else:
            buf.append(ch)
        i += 1
    if "".join(buf).strip():
        out.append("".join(buf).strip())
    return out


def parse_cvar_table():
    """Parse g_main.c's `static cvarTable_t gameCvarTable[] = { ... };`.
    Returns (entries, (start_line, end_line)). Entry fields follow
    cvarTable_t (g_main.c:17-25); trailing initializers may be omitted."""
    src = (GAME / "g_main.c").read_text(errors="replace")
    lines = src.splitlines()
    m = re.search(r"static\s+cvarTable_t\s+gameCvarTable\[\]\s*=\s*\{", src)
    if not m:
        sys.exit("gameCvarTable initializer not found in g_main.c")
    start_line = src[:m.start()].count("\n") + 1
    # find matching close brace of the initializer
    depth = 0
    i = src.index("{", m.start())
    for j in range(i, len(src)):
        if src[j] == "{":
            depth += 1
        elif src[j] == "}":
            depth -= 1
            if depth == 0:
                break
    body = src[i + 1:j]
    end_line = src[:j].count("\n") + 1
    body = strip_comments(preprocess(body))
    entries = []
    for grp in split_top_level(body):
        grp = grp.strip()
        if not (grp.startswith("{") and grp.endswith("}")):
            continue
        fields = split_top_level(grp[1:-1])
        # cvarTable_t: vmCvar, cvarName, defaultString, cvarFlags,
        #              modificationCount, trackChange, teamShader
        def fld(n, default="0"):
            return fields[n].strip() if n < len(fields) else default
        vmvar = fld(0, "NULL")
        vmvar = None if vmvar == "NULL" else vmvar.lstrip("&").strip()
        entries.append({
            "field": vmvar,
            "name": fld(1),
            "default": fld(2),
            "flags": re.sub(r"\s+", " ", fld(3)) or "0",
            "trackChange": fld(5, "qfalse") == "qtrue",
            "teamShader": fld(6, "qfalse") == "qtrue",
        })
    return entries, (start_line, end_line)


def c_string_or_macro(tok):
    """C initializer token -> (rust_literal, note). String literals pass
    through; known macros resolve with a cite; unknown stay TODO."""
    tok = tok.strip()
    if tok.startswith('"'):
        return tok, None
    if tok == "GAMEVERSION":
        return '"basejka"', "GAMEVERSION (g_local.h:29)"
    if tok == "__DATE__":
        return '"__DATE__"', "C compile-date macro — Land phase decides the dual"
    return f'"{tok}"', f"TODO unresolved macro `{tok}`"


