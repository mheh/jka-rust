def gen_ent_fn_enums(manifest, outdir):
    byname = defaultdict(list)
    for f in manifest["functions"]:
        byname[f["name"]].append(f)

    # field -> sorted distinct targets, from the manifest fn-ptr writes
    targets = defaultdict(set)
    for f in manifest["functions"]:
        for w in f["fnptr_writes"]:
            targets[w["field"]].add(w["target"])

    o = [GEN_NOTE]
    o.append("//! Entity fn-pointer dispatch as fn-ID enums + central match dispatch.")
    o.append("//!")
    o.append("//! Ruling 2 (docs/handoffs/jampgame-fork-discovery.md): per-field fn-ID")
    o.append("//! enums; `PartialEq` replaces Raven's fn-address compares; stored as")
    o.append("//! `Option<EntXxx>` where Raven stored a nullable fn pointer.")
    o.append("//! Field signatures source: `oracle/oracle/codemp/game/g_local.h:285-291`")
    o.append("//! Targets: fnsweep manifest fn-ptr write census (assignments in game/*.c).")
    o.append("//! Vehicle-vtable fields are excluded (fork-7 ruling: mp_bg enum dispatch).")
    o.append("#![allow(non_snake_case, non_camel_case_types, unused)]")
    o.append("")
    total_variants = 0
    for field, ename, params in ENT_FIELDS:
        tgts = sorted(targets.get(field, ()))
        total_variants += len(tgts)
        o.append(f"/// Raven `{field}` fn-pointer targets ({len(tgts)} distinct assigns")
        o.append(f"/// in game/*.c bodies).")
        o.append("///")
        o.append("/// Source: `oracle/oracle/codemp/game/g_local.h:285-291`")
        o.append("#[derive(Clone, Copy, PartialEq, Eq, Debug)]")
        o.append(f"pub enum {ename} {{")
        for t in tgts:
            hits = byname.get(t)
            if hits:
                h = hits[0]
                o.append(f"    /// `oracle/oracle/codemp/game/{h['file']}:{h['line']}`")
            else:
                o.append(f"    //TODO: Port {t}")
                o.append(f"    // Source: not a game/*.c definition (macro or"
                         f" out-of-module) — resolve at Land")
            o.append(f"    {t},")
        o.append("}")
        o.append("")
        sig = ", ".join(f"{n}: {t}" for n, t in params)
        args = ", ".join(n for n, _ in params)
        o.append(f"/// Central `{field}` dispatch (replaces `ent->{field}(...)`).")
        o.append(f"/// Faithful raw-pointer params for staging; the Land phase")
        o.append(f"/// re-shapes to (world, EntityId, …) per ruling 4.")
        o.append(f"pub fn dispatch_{field}(id: {ename}, {sig}) {{")
        o.append(f"    match id {{")
        for t in tgts:
            o.append(f"        {ename}::{t} => {t}({args}),")
        o.append("    }")
        o.append("}")
        o.append("")
    (outdir / "ent_fn_enums.rs").write_text("\n".join(o).rstrip() + "\n")
    return total_variants


# ======================================================== trap_wrappers.rs
def parse_trap_tokens():
    """trap_X -> (syscall token, g_syscalls.c line span) parsed from the
    oracle wrapper bodies."""
    src = (GAME / "g_syscalls.c").read_text(errors="replace")
    out = {}
    pat = re.compile(
        r"^[\w \t\*]*?\b(trap_\w+)\s*\([^;{]*\)\s*(?://[^\n]*)?\s*\{(.*?)^\}",
        re.M | re.S)
    for m in pat.finditer(src):
        name, body = m.group(1), m.group(2)
        sm = re.search(r"\bsyscall\s*\(\s*(\w+)", body)
        if sm:
            a = src[:m.start()].count("\n") + 1
            b = src[:m.end()].count("\n") + 1
            out[name] = (sm.group(1), f"{a}-{b}")
    return out


def parse_abi_traps():
    """trap name -> {return, params} from docs/abi-traps.md rows. Long rows
    wrap across physical lines, so match over the whole text (cells cannot
    contain backticks, so `[^`]*` is safe across newlines)."""
    text = (REPO / "docs" / "abi-traps.md").read_text()
    rows = {}
    for m in re.finditer(r"\|\s*\d+\s*\|\s*`(trap_\w+)`\s*\|\s*`([^`]+)`\s*\|"
                         r"\s*`([^`]*)`\s*\|", text):
        params = re.sub(r"\s+", " ", m.group(3)).strip()
        rows[m.group(1)] = {"return": m.group(2).strip(), "params": params}
    return rows


def camel(token):
    # capitalize segment starts AND letters after digits (abi convention:
    # G_G2TRACE -> GG2Trace, GHOUL2MODEL -> Ghoul2Model)
    out = []
    for p in token.split("_"):
        seg = p.capitalize()
        seg = re.sub(r"(\d)([a-z])", lambda m: m.group(1) + m.group(2).upper(), seg)
        out.append(seg)
    return "".join(out)


def abi_type_name(token, abi_dir):
    """Authoritative struct name from the abi file when present (the ABI is
    ground truth); camel heuristic otherwise."""
    f = abi_dir / f"{token}.rs"
    if f.exists():
        m = re.search(r"^pub struct (\w+);", f.read_text(), re.M)
        if m:
            return m.group(1)
    return camel(token)


def gen_trap_wrappers(manifest, outdir, abi_dir):
    traps = sorted({c["name"] for f in manifest["functions"]
                    for c in f["callees"]["syscall"]})
    tokens = parse_trap_tokens()
    sigrows = parse_abi_traps()
    have_abi = {p.stem for p in abi_dir.glob("*.rs")} if abi_dir.exists() else set()

    o = [GEN_NOTE]
    o.append("//! `mod trap` outbound-call wrappers for every trap_* the jampgame")
    o.append("//! manifest records a call to. One thin non-generic fn per call, the")
    o.append("//! frozen SEAM-D13 shape — copied verbatim from the live exemplar")
    o.append("//! `crates/mp/game/src/trap.rs` (skeleton branch). C signatures:")
    o.append("//! `docs/abi-traps.md`; token mapping: `oracle/oracle/codemp/game/g_syscalls.c`.")
    o.append("#![allow(non_snake_case, unused)]")
    o.append("")
    # A `trap_`-named symbol DEFINED in game/*.c OUTSIDE g_syscalls.c is a
    # module-local helper (e.g. trap_Cvar_VariableValue, g_bot.c:36), not a
    # seam wrapper — ported as a normal function, no SEAM-D13 wrapper.
    defined_in_module = {f["name"] for f in manifest["functions"]
                         if f["file"] != "g_syscalls.c"}

    missing_token, missing_abi, module_local = [], [], []
    uses, fns = [], []
    for t in traps:
        if t in defined_in_module:
            module_local.append(t)
            continue
        tok = tokens.get(t)
        if tok is None:
            missing_token.append(t)
            continue
        token, span = tok
        ty = abi_type_name(token, abi_dir)
        if token not in have_abi:
            missing_abi.append((t, token))
        short = t[len("trap_"):]
        sig = sigrows.get(t)
        csig = (f"`{sig['return']} {t}({sig['params']})`" if sig
                else "(not in abi-traps.md)")
        uses.append(f"use mp_abi::game::syscalls::{token}::{ty};")
        fns.append("\n".join([
            f"/// Raven `{t}` (`g_syscalls.c:{span}`) — `{token}`.",
            f"/// C: {csig}",
            f"pub fn {short}(",
            f"    engine: &Engine,",
            f"    args: <{ty} as OutboundSysCall>::Args,",
            f") -> <{ty} as OutboundSysCall>::Output {{",
            f"    // UFCS spelling of the frozen `engine.execute(args)` — the bare",
            f"    // method call cannot infer `C` from `Args` alone (SEAM-D13).",
            f"    <Engine as Execute<{ty}>>::execute(engine, args)",
            f"}}",
        ]))
    o.extend(sorted(uses))
    o.append("use mp_abi::{Execute, OutboundSysCall};")
    o.append("use mp_engine_select::Engine;")
    o.append("")
    o.append("\n\n".join(fns))
    if module_local:
        o.append("")
        o.append("// trap_-named MODULE-LOCAL helpers (defined in game/*.c, not")
        o.append("// g_syscalls.c) — ported as normal functions, no wrapper here:")
        for t in module_local:
            o.append(f"//   {t}")
    if missing_token:
        o.append("")
        for t in missing_token:
            o.append(f"//TODO: Port {t}")
            o.append(f"// Source: oracle/oracle/codemp/game/g_syscalls.c — no "
                     f"syscall() token found by fngen.py; resolve by hand")
    if missing_abi:
        o.append("")
        o.append("// Tokens above with no mp_abi definition yet (wrapper emitted;")
        o.append("// needs the abi Args/Output type before it compiles):")
        for t, token in missing_abi:
            o.append(f"//   {token} ({t})")
    (outdir / "trap_wrappers.rs").write_text("\n".join(o) + "\n")
    return (len(traps) - len(missing_token) - len(module_local),
            missing_token, [t for _, t in missing_abi], module_local)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    here = Path(__file__).resolve().parent
    ap.add_argument("--manifest", default=str(here / "out" / "jampgame-fn-manifest.json"))
    ap.add_argument("--out", default=str(here / "out" / "gen"))
    ap.add_argument("--abi-dir", default=str(
        REPO / ".claude" / "worktrees" / "agent-a43cc53200d2fdf54" /
        "crates" / "mp" / "abi" / "src" / "game" / "syscalls"))
    args = ap.parse_args()

    manifest = json.loads(Path(args.manifest).read_text())
    outdir = Path(args.out)
    outdir.mkdir(parents=True, exist_ok=True)

    rows, handles = gen_game_cvars(outdir)
    print(f"[fngen] game_cvars.rs: {rows} table rows, {handles} GameCvars fields")
    variants = gen_ent_fn_enums(manifest, outdir)
    print(f"[fngen] ent_fn_enums.rs: {variants} variants across "
          f"{len(ENT_FIELDS)} enums")
    n, no_token, no_abi, mod_local = gen_trap_wrappers(
        manifest, outdir, Path(args.abi_dir))
    print(f"[fngen] trap_wrappers.rs: {n} wrappers"
          + (f", {len(mod_local)} module-local trap_ helpers: {mod_local}"
             if mod_local else "")
          + (f", {len(no_token)} traps lacked a token: {no_token}" if no_token else "")
          + (f", {len(no_abi)} tokens missing mp_abi defs" if no_abi else ""))


if __name__ == "__main__":
    main()
