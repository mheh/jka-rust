/// Raven `NAV_Bypass`.
///
/// Source: `oracle/oracle/codemp/game/g_nav.c:589-661`
pub fn NAV_Bypass(
    ctx: GameContext<'_>,
    self_: *mut gentity_t,
    blocker: *mut gentity_t,
    blocked_dir: vec3_t,
    blocked_dist: f32,
    movedir: &mut vec3_t,
) -> qboolean {
    unsafe {
        let mut right = [0.0f32; 3];

        // Draw debug info if requested
        if (*ctx.world).globals.NAVDEBUG_showCollision != 0 {
            G_DrawEdge(
                (*self_).r.currentOrigin,
                (*blocker).r.currentOrigin,
                EDGE_NORMAL,
            );
        }

        AngleVectors((*self_).r.currentAngles, None, Some(&mut right), None);

        // Get the blocked direction
        let yaw = vectoyaw(blocked_dir);

        // Get the avoid radius
        let avoidRadius = ((*blocker).r.maxs[0] * (*blocker).r.maxs[0]
            + (*blocker).r.maxs[1] * (*blocker).r.maxs[1])
            .sqrt()
            + ((*self_).r.maxs[0] * (*self_).r.maxs[0] + (*self_).r.maxs[1] * (*self_).r.maxs[1])
                .sqrt();

        // See if we're inside our avoidance radius
        let mut arcAngle = if blocked_dist <= avoidRadius {
            135.0
        } else {
            (avoidRadius / blocked_dist) * 90.0
        };

        // Check to see what dir the other guy is moving in (if any) and pick the opposite dir
        if !(*blocker).client.is_null() {
            let blocker_client = (*blocker).client as *mut gclient_t;
            if VectorCompare((*blocker_client).ps.velocity, [0.0, 0.0, 0.0]) == 0 {
                let mut blocker_movedir = [0.0f32; 3];
                VectorNormalize2((*blocker_client).ps.velocity, &mut blocker_movedir);
                let dot = crate::q_math::_DotProduct(blocker_movedir, blocked_dir);
                if dot < 0.35 && dot > -0.35 {
                    // he's moving to the side of me
                    let mut block_pos = [0.0f32; 3];
                    let mut tr: trace_t = core::mem::zeroed();
                    crate::q_math::_VectorScale(blocker_movedir, -1.0, &mut blocker_movedir);
                    crate::q_math::_VectorMA(
                        (*self_).r.currentOrigin,
                        blocked_dist,
                        blocker_movedir,
                        &mut block_pos,
                    );
                    if NAV_CheckAhead(
                        ctx,
                        self_,
                        block_pos,
                        &mut tr as *mut trace_t,
                        ((*self_).clipmask & !CONTENTS_BODY) | CONTENTS_BOTCLIP,
                    ) != 0
                    {
                        crate::q_math::_VectorCopy(blocker_movedir, movedir);
                        return qtrue;
                    }
                }
            }
        }

        let dot = crate::q_math::_DotProduct(blocked_dir, right);

        // Go right on the first try if that works better
        if dot < 0.0 {
            arcAngle *= -1.0;
        }

        // Test full, best position first
        if NAV_TestBypass(
            ctx,
            self_,
            AngleNormalize360(yaw + arcAngle),
            blocked_dist,
            movedir,
        ) != 0
        {
            return qtrue;
        }

        // Try a smaller arc
        if NAV_TestBypass(
            ctx,
            self_,
            AngleNormalize360(yaw + (arcAngle * 0.5)),
            blocked_dist,
            movedir,
        ) != 0
        {
            return qtrue;
        }

        // Try the other direction
        if NAV_TestBypass(
            ctx,
            self_,
            AngleNormalize360(yaw + (arcAngle * -1.0)),
            blocked_dist,
            movedir,
        ) != 0
        {
            return qtrue;
        }

        // Try the other direction more precisely
        if NAV_TestBypass(
            ctx,
            self_,
            AngleNormalize360(yaw + ((arcAngle * -1.0) * 0.5)),
            blocked_dist,
            movedir,
        ) != 0
        {
            return qtrue;
        }

        // Unable to go around
        qfalse
    }
}

/// Raven `NAV_MoveBlocker`.
