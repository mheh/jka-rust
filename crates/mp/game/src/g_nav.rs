/// Raven `NPC_Blocked`.
///
/// Source: `oracle/oracle/codemp/game/g_nav.c:68-104`
pub fn NPC_Blocked(ctx: GameContext<'_>, self_: *mut gentity_t, blocker: *mut gentity_t) {
    unsafe {
        if (*self_).NPC.is_null() {
            return;
        }
        let npc = (*self_).NPC as *mut gNPC_t;

        // Don't do this too often
        if (*npc).blockedSpeechDebounceTime > (*ctx.world).level.time {
            return;
        }

        // Attempt to run any blocked scripts
        // PORT-NOTE(missing-const): BSET_BLOCKED (bset_t enum value) not
        // resolved anywhere in the crate graph; written as cited.
        if G_ActivateBehavior(ctx, self_, BSET_BLOCKED as c_int) != 0 {
            return;
        }

        // If this is one of our enemies, then just attack him
        if !(*blocker).client.is_null() {
            let blocker_client = (*blocker).client as *mut gclient_t;
            let self_client = (*self_).client as *mut gclient_t;
            if (*blocker_client).playerTeam == (*self_client).enemyTeam {
                G_SetEnemy(ctx, self_, blocker);
                return;
            }
        }

        // PORT-NOTE(dead-oracle-code): the player-blocked voice-event branch's
        // body is entirely commented out in the oracle (`//G_AddVoiceEvent(...)`)
        // — no live behavior to transcribe beyond the (side-effect-free) guard.

        (*npc).blockedSpeechDebounceTime = (*ctx.world).level.time
            + MIN_BLOCKED_SPEECH_TIME
            + ((*ctx.world).bg_state.rng.random() * 4000.0) as c_int;
        (*npc).blockingEntNum = (*blocker).s.number;
    }
}

/// Raven `NPC_SetMoveGoal`.
///
/// Source: `oracle/oracle/codemp/game/g_nav.c:112-159`
pub fn NPC_SetMoveGoal(
    ctx: GameContext<'_>,
    ent: *mut gentity_t,
    point: vec3_t,
    radius: c_int,
    isNavGoal: qboolean,
    combatPoint: c_int,
    targetEnt: *mut gentity_t,
) {
    unsafe {
        if (*ent).NPC.is_null() {
            return;
        }
        let npc = (*ent).NPC as *mut gNPC_t;

        let temp_goal_id = match (*npc).tempGoal {
            Some(id) => id, // must still have a goal
            None => return,
        };
        let base = (*ctx.world).g_entities.as_mut_ptr() as *const gentity_t;
        let temp_goal = &mut (*ctx.world).g_entities[temp_goal_id.index()] as *mut gentity_t;

        // Copy the origin
        crate::q_math::_VectorCopy(point, &mut (*temp_goal).r.currentOrigin);

        // Copy the mins and maxs to the tempGoal
        crate::q_math::_VectorCopy((*ent).r.mins, &mut (*temp_goal).r.mins);
        crate::q_math::_VectorCopy((*ent).r.mins, &mut (*temp_goal).r.maxs);

        (*temp_goal).target = core::ptr::null_mut();
        (*temp_goal).clipmask = (*ent).clipmask;
        (*temp_goal).flags &= !FL_NAVGOAL;
        if !targetEnt.is_null() && (*targetEnt).waypoint >= 0 {
            (*temp_goal).waypoint = (*targetEnt).waypoint;
        } else {
            (*temp_goal).waypoint = WAYPOINT_NONE;
        }
        (*temp_goal).noWaypointTime = 0;

        if isNavGoal != 0 {
            debug_assert!((*temp_goal).parent.is_some());
            (*temp_goal).flags |= FL_NAVGOAL;
        }

        (*temp_goal).combatPoint = combatPoint;
        (*temp_goal).enemy = ent_id_opt(base, targetEnt);

        (*npc).goalEntity = Some(temp_goal_id);
        (*npc).goalRadius = radius;

        trap::LinkEntity(ctx.engine, GLinkentityArgs::new(temp_goal));
    }
}

/// Raven `NAV_HitNavGoal`.
///
/// Source: `oracle/oracle/codemp/game/g_nav.c:167-214`
pub fn NAV_HitNavGoal(
    point: vec3_t,
    mins: vec3_t,
    maxs: vec3_t,
    dest: vec3_t,
    radius: c_int,
    flying: qboolean,
) -> qboolean {
    let mut radius = radius;
    if radius & NAVGOAL_USE_RADIUS != 0 {
        radius &= !NAVGOAL_USE_RADIUS;
        if flying == 0 {
            // Allow for a little z difference
            let mut diff = [0.0f32; 3];
            crate::q_math::_VectorSubtract(point, dest, &mut diff);
            if diff[2].abs() <= 24.0 {
                diff[2] = 0.0;
            }
            return (VectorLengthSquared(diff) <= (radius * radius) as f32) as qboolean;
        } else {
            // must hit exactly
            return (DistanceSquared(dest, point) <= (radius * radius) as f32) as qboolean;
        }
    } else {
        // Construct a dummy bounding box from our radius value
        let mut dmins = [0.0f32; 3];
        let mut dmaxs = [0.0f32; 3];
        let r = radius as f32;
        dmins = [-r, -r, -r];
        dmaxs = [r, r, r];

        // Translate it
        let mut dmins2 = [0.0f32; 3];
        let mut dmaxs2 = [0.0f32; 3];
        crate::q_math::_VectorAdd(dmins, dest, &mut dmins2);
        crate::q_math::_VectorAdd(dmaxs, dest, &mut dmaxs2);

        // Translate the starting box
        let mut pmins = [0.0f32; 3];
        let mut pmaxs = [0.0f32; 3];
        crate::q_math::_VectorAdd(point, mins, &mut pmins);
        crate::q_math::_VectorAdd(point, maxs, &mut pmaxs);

        // See if they overlap
        G_BoundsOverlap(pmins, pmaxs, dmins2, dmaxs2)
    }
}

/// Raven `NAV_ClearPathToPoint`.
///
/// Source: `oracle/oracle/codemp/game/g_nav.c:222-344`
pub fn NAV_ClearPathToPoint(
    ctx: GameContext<'_>,
    self_: *mut gentity_t,
    pmins: vec3_t,
    pmaxs: vec3_t,
    point: vec3_t,
    clipmask: c_int,
    okToHitEntNum: c_int,
) -> qboolean {
    unsafe {
        let mut mins = [0.0f32; 3];
        let mut maxs = [0.0f32; 3];
        let mut clipmask = clipmask;
        let mut trace: trace_t = core::mem::zeroed();

        // Test if they're even conceivably close to one another
        if trap::InPVS(
            ctx.engine,
            GInPvsArgs::new(
                &(*self_).r.currentOrigin as *const vec3_t,
                &point as *const vec3_t,
            ),
        ) == 0
        {
            return qfalse;
        }

        if (*self_).flags & FL_NAVGOAL != 0 {
            let parent = match (*self_).parent {
                Some(id) => &mut (*ctx.world).g_entities[id.index()] as *mut gentity_t,
                None => {
                    // SHOULD NEVER HAPPEN!!!
                    debug_assert!((*self_).parent.is_some());
                    return qfalse;
                }
            };
            crate::q_math::_VectorCopy((*parent).r.mins, &mut mins);
            crate::q_math::_VectorCopy((*parent).r.maxs, &mut maxs);
        } else {
            crate::q_math::_VectorCopy(pmins, &mut mins);
            crate::q_math::_VectorCopy(pmaxs, &mut maxs);
        }

        if !(*self_).client.is_null() || ((*self_).flags & FL_NAVGOAL != 0) {
            // Clients can step up things, or if this is a navgoal check, a client will be using this info
            mins[2] += STEPSIZE;

            // don't let box get inverted
            if mins[2] > maxs[2] {
                mins[2] = maxs[2];
            }
        }

        if (*self_).flags & FL_NAVGOAL != 0 {
            let parent = match (*self_).parent {
                Some(id) => &mut (*ctx.world).g_entities[id.index()] as *mut gentity_t,
                None => return qfalse,
            };
            // Trace from point to navgoal
            trap::Trace(
                ctx.engine,
                GTraceArgs::new(
                    &mut trace as *mut trace_t,
                    &point as *const vec3_t,
                    &mins as *const vec3_t,
                    &maxs as *const vec3_t,
                    &(*self_).r.currentOrigin as *const vec3_t,
                    (*parent).s.number,
                    (clipmask | CONTENTS_MONSTERCLIP | CONTENTS_BOTCLIP) & !CONTENTS_BODY,
                ),
            );
            if trace.startsolid != 0 && (trace.contents & CONTENTS_BOTCLIP) != 0 {
                // started inside do not enter, so ignore them
                clipmask &= !CONTENTS_BOTCLIP;
                trap::Trace(
                    ctx.engine,
                    GTraceArgs::new(
                        &mut trace as *mut trace_t,
                        &point as *const vec3_t,
                        &mins as *const vec3_t,
                        &maxs as *const vec3_t,
                        &(*self_).r.currentOrigin as *const vec3_t,
                        (*parent).s.number,
                        (clipmask | CONTENTS_MONSTERCLIP) & !CONTENTS_BODY,
                    ),
                );
            }

            if trace.startsolid != 0 || trace.allsolid != 0 {
                return qfalse;
            }

            // Made it
            if trace.fraction == 1.0 {
                return qtrue;
            }

            if okToHitEntNum != ENTITYNUM_NONE && trace.entityNum as c_int == okToHitEntNum {
                return qtrue;
            }

            // Okay, didn't get all the way there, let's see if we got close enough:
            if NAV_HitNavGoal(
                (*self_).r.currentOrigin,
                (*parent).r.mins,
                (*parent).r.maxs,
                trace.endpos,
                (*(*ctx.world).globals.NPCInfo).goalRadius,
                FlyingCreature(parent),
            ) != 0
            {
                return qtrue;
            } else if (*ctx.world).globals.NAVDEBUG_showCollision != 0 {
                if (trace.entityNum as c_int) < ENTITYNUM_WORLD
                    && (*ctx.world).g_entities[trace.entityNum as usize].s.eType
                        != ET_MOVER as c_int
                {
                    let blocker =
                        &mut (*ctx.world).g_entities[trace.entityNum as usize] as *mut gentity_t;
                    let mut p1 = [0.0f32; 3];
                    let mut p2 = [0.0f32; 3];
                    G_DrawEdge(point, trace.endpos, EDGE_PATH);
                    crate::q_math::_VectorAdd(
                        (*blocker).r.mins,
                        (*blocker).r.currentOrigin,
                        &mut p1,
                    );
                    crate::q_math::_VectorAdd(
                        (*blocker).r.maxs,
                        (*blocker).r.currentOrigin,
                        &mut p2,
                    );
                    G_CubeOutline(p1, p2, FRAMETIME, 0x0000ff, 0.5);
                }
            }
        } else {
            trap::Trace(
                ctx.engine,
                GTraceArgs::new(
                    &mut trace as *mut trace_t,
                    &(*self_).r.currentOrigin as *const vec3_t,
                    &mins as *const vec3_t,
                    &maxs as *const vec3_t,
                    &point as *const vec3_t,
                    (*self_).s.number,
                    clipmask | CONTENTS_MONSTERCLIP | CONTENTS_BOTCLIP,
                ),
            );
            if trace.startsolid != 0 && (trace.contents & CONTENTS_BOTCLIP) != 0 {
                clipmask &= !CONTENTS_BOTCLIP;
                trap::Trace(
                    ctx.engine,
                    GTraceArgs::new(
                        &mut trace as *mut trace_t,
                        &(*self_).r.currentOrigin as *const vec3_t,
                        &mins as *const vec3_t,
                        &maxs as *const vec3_t,
                        &point as *const vec3_t,
                        (*self_).s.number,
                        clipmask | CONTENTS_MONSTERCLIP,
                    ),
                );
            }

            if trace.startsolid == 0 && trace.allsolid == 0 && trace.fraction == 1.0 {
                return qtrue;
            }

            if okToHitEntNum != ENTITYNUM_NONE && trace.entityNum as c_int == okToHitEntNum {
                return qtrue;
            }

            if (*ctx.world).globals.NAVDEBUG_showCollision != 0
                && (trace.entityNum as c_int) < ENTITYNUM_WORLD
                && (*ctx.world).g_entities[trace.entityNum as usize].s.eType != ET_MOVER as c_int
            {
                let blocker =
                    &mut (*ctx.world).g_entities[trace.entityNum as usize] as *mut gentity_t;
                let mut p1 = [0.0f32; 3];
                let mut p2 = [0.0f32; 3];
                G_DrawEdge((*self_).r.currentOrigin, trace.endpos, EDGE_PATH);
                crate::q_math::_VectorAdd((*blocker).r.mins, (*blocker).r.currentOrigin, &mut p1);
                crate::q_math::_VectorAdd((*blocker).r.maxs, (*blocker).r.currentOrigin, &mut p2);
                G_CubeOutline(p1, p2, FRAMETIME, 0x0000ff, 0.5);
            }
        }

        qfalse
    }
}

